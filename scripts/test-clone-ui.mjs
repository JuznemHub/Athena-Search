import assert from 'node:assert/strict';
import { paginateCloneTopics, renderCloneProgress, renderCloneStatistics } from '../worker/clone-ui.js';
const plain = (html) => html.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"');
const source = { sourceName: 'Reading room', chatId: '-1001234567890', destination: 'Community archive' };
const counters = { messages: 10, links: 11, linkPosts: 4, files: 6, copiedMessages: 5, savedLinkPosts: 3, savedLinks: 7, savedFiles: 2, savedPdfs: 1, duplicates: 4, failed: 2, errorCategories: { database: 2 } };
const activeHtml = renderCloneProgress({ ...source, status: 'running', topicsTotal: 237, topicsDone: 12, currentTopic: { id: '3', name: 'Current discussion' }, processed: 5, total: 10, counters, overallCounters: { ...counters, messages: 250, savedLinks: 77, total: 500 } });
const active = plain(activeHtml);
assert.match(activeHtml, /<table/);
assert.match(activeHtml, /href="https:\/\/t.me\/c\/1234567890\/1"/);
assert.match(active, /Current topic: #3 Current discussion/);
assert.match(active, /50%/);
assert.match(active, /Topics completed: 12 \/ 237/);
assert.ok((active.match(/[█░]{10}/g) || []).length >= 2, 'Current topic and overall topic bars are visible');
assert.match(active, /Saved URLs7/);
assert.match(active, /Saved URLs77/);
assert.match(active, /Encountered URLs11/);
assert.match(active, /Failed2/);
assert.match(active, /database: 2/);
const both = plain(renderCloneProgress({ ...source, destination: 'Community + Personal brain', target: 'both', status: 'running', counters, processed: 5, total: 10 }));
assert.match(both, /per destination/);
assert.match(both, /once per source message/);
const completed = plain(renderCloneProgress({ ...source, status: 'done', topicsTotal: 237, topicsDone: 237, overallCounters: { ...counters, messages: 250 }, counters: { messages: 999 }, processed: 999, total: 1000 }));
assert.match(completed, /100%/);
assert.match(completed, /Encountered messages250/);
assert.doesNotMatch(completed, /999|1,000/);
const completedTopic = plain(renderCloneProgress({ ...source, status: 'Topic completed', topicsTotal: 3, topicsDone: 1, currentTopic: { id: '1', name: 'General' }, processed: 10, total: 10, counters, overallCounters: counters }));
assert.match(completedTopic, /General/);
assert.match(completedTopic, /100%/);
assert.match(completedTopic, /Saved URLs7/);
const unknown = plain(renderCloneProgress({ ...source, status: 'scanning', processed: 13, total: null, counters: { messages: 13 } }));
assert.match(unknown, /total unknown/);
assert.doesNotMatch(unknown, /NaN|Infinity|%/);
const stats = plain(renderCloneStatistics({ ...source, username: 'reading', members: 451, counters, measurement: 'accessible-history', complete: true }));
assert.match(stats, /Members \(Telegram-reported\): 451/);
assert.match(stats, /exact counts from accessible history/);
assert.match(stats, /Encountered link posts4/);
assert.match(stats, /Encountered URLs11/);
assert.doesNotMatch(stats, /Saved URLs|Copied messages/);
const incomplete = plain(renderCloneStatistics({ ...source, counters, measurement: 'accessible-history', complete: false }));
assert.match(incomplete, /Scan incomplete/);
assert.doesNotMatch(incomplete, /exact counts/);
const hostile = renderCloneProgress({ sourceName: '<script>bad</script>', chatId: '<chat>', destination: '<bad>', status: 'running', counters });
assert.doesNotMatch(hostile, /<script>/);
assert.match(hostile, /&lt;script&gt;/);
const topics = Array.from({ length: 237 }, (_, i) => ({ id: String(i + 1), name: 'Topic ' + (i + 1) }));
for (const items of [topics, topics.map(t => ({ ...t, name: 'A𐐀<&"'.repeat(1000) }))]) {
  const first = paginateCloneTopics(items);
  const all = [];
  for (let p = 0; p < first.pages; p++) {
    const page = paginateCloneTopics(items, p);
    assert.ok(page.topics.length <= 100);
    assert.ok(page.text.length <= 4096);
    all.push(...page.topics);
  }
  assert.deepEqual(all, items, 'Every topic reachable exactly once through pagination');
  assert.equal(paginateCloneTopics(items, -1).page, 0);
  assert.equal(paginateCloneTopics(items, 9999).page, first.pages - 1);
}
console.log('Clone UI consumer-output fixtures passed.');
